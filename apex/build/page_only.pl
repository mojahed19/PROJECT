#!/usr/bin/perl
# =====================================================================
#  page_only.pl - ملف تثبيت لصفحات محددة فقط (Page / Component export)
#  بدل استبدال التطبيق كاملاً، حتى لا تضيع تعديلات المستخدم في APEX Builder.
#
#  الاستخدام:
#    perl apex/build/page_only.pl <offset> <workspace_id> <page> [page ...]  > apex/app/pages_only.sql
#
#  <offset> : إزاحة المعرّفات في التطبيق المثبّت = (معرّف مكوّن في APEX) − (معرّفه في آخر f100.sql مثبّت)
#             مثال: SELECT region_id FROM apex_application_page_regions WHERE application_id = 115 AND page_id = 10
#  المعرّفات الخاصة بالصفحة (مناطق/عناصر/أزرار/عمليات) تُزاح بمقدار إضافي حتى لا تتعارض مع صفحات أخرى؛
#  المراجع المشتركة (القوالب، القوائم، الصلاحيات) تبقى كما هي فتشير لمكوّنات التطبيق الحالية.
# =====================================================================
use strict;
use warnings;

my ($offset, $ws_live, @pages) = @ARGV;
die "usage: page_only.pl <offset> <workspace_id> <page>\n" unless defined $offset && $ws_live && @pages;
# معالج الاستيراد في APEX يثبّت الصفحة الأولى فقط من الملف: ملف مستقل لكل صفحة
die "one page per file: APEX page import installs only the first page\n" if @pages > 1;
# إزاحة إضافية لمعرّفات مكوّنات الصفحة ، مختلفة في كل بناء (حسب الوقت) حتى لا تتعارض
# مع صفحات ثُبّتت بهذه الطريقة سابقاً (ترقيم المولّد يتغير بين البناءات)
my $LOCAL_SHIFT = (time() % 1_000_000 + 1) * 10_000_000;

my $file = "$0"; $file =~ s{build/page_only\.pl$}{app/f100.sql};
open my $fh, '<', $file or die "$file: $!";
local $/; my $all = <$fh>; close $fh;

my $ws = $ws_live;   # مساحة العمل الفعلية: SELECT workspace_id FROM apex_workspaces WHERE workspace = 'MOSS'
my ($app) = $all =~ /p_default_application_id=>(\d+)/;
my ($ver) = $all =~ /p_version_yyyy_mm_dd=>'([^']+)'/;
my ($rel) = $all =~ /p_release=>'([^']+)'/;

my $out = <<"HDR";
prompt --application/set_environment
set define off verify off feedback off
whenever sqlerror exit sql.sqlcode rollback
--------------------------------------------------------------------------------
-- Oracle APEX page export - generated by apex/build/page_only.pl
--   Manifest
@{[ join("\n", map { "--     PAGE: $_" } @pages) ]}
--------------------------------------------------------------------------------
begin
wwv_flow_imp.import_begin (
 p_version_yyyy_mm_dd=>'$ver'
,p_release=>'$rel'
,p_default_workspace_id=>$ws
,p_default_application_id=>$app
,p_default_id_offset=>$offset
,p_default_owner=>'MOSS'
);
end;
/
HDR

# الصلاحيات تُربط بالاسم لا بالرقم: ترقيم المولّد يتغير كلما تغيّرت قائمة التنقل (وهي قبل الصلاحيات) ،
# فتشير الصفحة لصلاحية أخرى (حدث 2026-11-25: الصفحة 10 صارت IS_HR).
# معرّفات الصلاحيات في التطبيق المثبّت 115:
#   SELECT authorization_scheme_name, authorization_scheme_id FROM apex_application_authorization WHERE application_id = 115
my %LIVE_AUTH = (IS_GM => 9204490307775087, IS_ACCOUNTANT => 9204490307775088, IS_HR => 9204490307775089, IS_STORE => 9204490307775090);
my %auth_map;   # معرّف الصلاحية في f100.sql => المعرّف الذي يصبح بعد الإزاحة معرّفها الفعلي
while ($all =~ /create_security_scheme\(\s*p_id=>wwv_flow_imp\.id\((\d+)\)\s*,p_name=>'([^']+)'/g) {
  die "unknown authorization scheme $2: add its live id to %LIVE_AUTH\n" unless $LIVE_AUTH{$2};
  $auth_map{$1} = $LIVE_AUTH{$2} - $offset;
}
die "no authorization schemes found in f100.sql\n" unless %auth_map;

for my $p (@pages) {
  my $tag = sprintf('page_%05d', $p);
  my ($sec) = $all =~ m{(^prompt --application/pages/$tag\n.*?)(?=^prompt --application/)}ms
    or die "page $p not found";
  # معرّفات مكوّنات الصفحة = كل p_id المعرّف داخل القسم
  my %local = map { $_ => 1 } ($sec =~ /p_id=>wwv_flow_imp\.id\((\d+)\)/g);
  $sec =~ s/(p_required_role|p_security_scheme|p_authorization_scheme)=>wwv_flow_imp\.id\((\d+)\)/
            "$1=>wwv_flow_imp.id(" . ($auth_map{$2} or die "page $p: unknown authorization id $2\n") . ')'/ge;
  $sec =~ s/(?<!_required_role=>)(?<!_security_scheme=>)(?<!_authorization_scheme=>)wwv_flow_imp\.id\((\d+)\)/'wwv_flow_imp.id(' . ($local{$1} ? $1 + $LOCAL_SHIFT : $1) . ')'/ge;
  $out .= sprintf("prompt --application/pages/delete_%05d\nbegin\nwwv_flow_imp_page.remove_page (p_flow_id=>wwv_flow.g_flow_id, p_page_id=>%d);\nend;\n/\n", $p, $p);
  $out .= $sec;
}

$out .= <<'END';
prompt --application/end_environment
begin
wwv_flow_imp.import_end(p_auto_install_sup_obj => nvl(wwv_flow_application_install.get_auto_install_sup_obj, false));
commit;
end;
/
set verify on feedback on define on
prompt  ...done
END
print $out;
