  my $auth_fn = <<'PLSQL';
FUNCTION auth_user (p_username IN VARCHAR2, p_password IN VARCHAR2) RETURN BOOLEAN IS
  l_ok NUMBER;
BEGIN
  SELECT COUNT(*) INTO l_ok
  FROM   app_users u
  WHERE  u.user_name = UPPER(TRIM(p_username))
  AND    u.is_active = 'Y'
  AND    u.password_hash = RAWTOHEX(STANDARD_HASH(UPPER(TRIM(p_username)) || ':' || p_password, 'SHA256'));
  RETURN l_ok = 1;
END;
PLSQL
