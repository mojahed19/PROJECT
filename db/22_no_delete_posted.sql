-- =====================================================================
--  22_no_delete_posted.sql  -  إزالة منع الحذف على مستوى قاعدة البيانات
--   قرار المستخدم (2026-11-26): التقييد يكون في الشاشات فقط. من داخل قاعدة البيانات يُسمح بالحذف والتعديل
--   لكل البيانات (حتى المرحّلة والمعتمدة) لأغراض التنظيف والصيانة.
--   الشاشات تبقى مقيّدة: لا تحذف ولا تعدّل إلا المسودة أو المعاد للتصحيح ، والمرحّل يُصحَّح بالعكس.
--   سجل التدقيق (db/20) يبقى يسجّل الحذف والتعديل ولا يمنعهما.
--   هذا السكربت يحذف Triggers المنع (trg_nodel_*) إن وُجدت من نسخة سابقة ، وآمن لإعادة التشغيل.
-- =====================================================================
SET DEFINE OFF

BEGIN
  FOR t IN (SELECT trigger_name FROM user_triggers WHERE trigger_name LIKE 'TRG\_NODEL\_%' ESCAPE '\') LOOP
    EXECUTE IMMEDIATE 'DROP TRIGGER ' || t.trigger_name;
    DBMS_OUTPUT.PUT_LINE('DROPPED ' || t.trigger_name);
  END LOOP;
END;
/
